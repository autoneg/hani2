"""The texts behind the ``?`` buttons of the admin console's project and study editor.

One registry, :data:`HELP`, keyed by **setting id** (``study_mode``, ``pairing.assign``,
``scheduling.assistants``, ``scores.missing``, …). Each entry has a ``title``, a one-line
``summary`` (the row's grey hint) and Markdown ``details`` (shown in the dialog; maths in ``$…$``
and tables are allowed). The editor fetches them once from ``GET /api/admin/help``.

* :data:`REQUIRED` lists every editor choice that is not self-explanatory. A backend test checks
  that each one has an entry, and a frontend test checks that each id occurs in the editor's
  sources, so a new choice cannot ship without its ``?``.
* The Settings reference page of the docs is generated from the same registry
  (``python -m hani2.help_texts docs/guide/settings-reference.md``), so the docs and the ``?``
  texts never disagree.
* Scheduling methods keep their own registry (:mod:`hani2.scheduling`); an entry that names one
  of its dimensions in ``scheduling`` gets the methods' summaries appended in the dialog and a
  link in the docs. Criteria use their catalogue text (:mod:`hani2.evaluation.criteria`).

Rows whose meaning is plain (full name, link, start and end, year, organizer, contact, the time
limits) have no entry.
"""

