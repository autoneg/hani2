def anchor(key: str) -> str:
    return "setting-" + key.replace(".", "-").replace("_", "-")


def markdown_reference() -> str:
    """The generated part of ``docs/guide/settings-reference.md``."""
    from hani2 import scheduling

    out: list[str] = []
    for sec in SECTIONS:
        entries = [(k, h) for k, h in HELP.items() if h.section == sec]
        if not entries:
            continue
        out.append(f"## {sec}\n")
        out.append("| Setting | Key | Summary |\n|---|---|---|")
        out += [f"| [{h.title}](#{anchor(k)}) | `{h.key or k}` | {h.summary.replace('|', '/')} |" for k, h in entries]
        out.append("")
        for k, h in entries:
            out.append(f"### {h.title} {{#{anchor(k)}}}\n")
            out.append(f"`{h.key or k}`: *{h.summary}*\n")
            if h.details:
                out.append(h.details.rstrip() + "\n")
            if h.scheduling:
                rows = [f"| `{m.key}` | {m.summary.replace('|', '/')} |" for m in scheduling.methods(h.scheduling)]
                out.append("| Method | Summary |\n|---|---|\n" + "\n".join(rows) + "\n")
            if h.docs:
                out.append(f"More: [{h.docs.split('#')[0].removesuffix('.md').replace('-', ' ').capitalize()}]({h.docs}).\n")
    return "\n".join(out).rstrip() + "\n"


def write_docs(path: str | Path) -> bool:
    """Rewrite the generated part of the docs page; ``True`` when it changed."""
    p = Path(path)
    text = p.read_text(encoding="utf-8")
    a, b = text.index(DOCS_START), text.index(DOCS_END)
    new = text[: a + len(DOCS_START)] + "\n\n" + markdown_reference() + "\n" + text[b:]
    if new != text:
        p.write_text(new, encoding="utf-8")
        return True
    return False


def docs_section(text: str) -> str:
    a, b = text.index(DOCS_START), text.index(DOCS_END)
    return text[a + len(DOCS_START): b].strip() + "\n"


