def problems() -> list[str]:
    """What is wrong with the registry: required ids without an entry, summaries longer than a line."""
    out = [f"{k}: required but has no help text" for k in REQUIRED if k not in HELP]
    for k, h in HELP.items():
        if not h.title or not h.summary:
            out.append(f"{k}: needs a title and a summary")
        if "\n" in h.summary or len(h.summary) > 160:
            out.append(f"{k}: the summary must be one line (at most 160 characters)")
        if h.section not in SECTIONS:
            out.append(f"{k}: unknown section {h.section!r}")
    return out


def api_payload() -> dict[str, Any]:
    """What ``GET /api/admin/help`` returns."""
    return {"help": {k: h.to_dict() for k, h in HELP.items()}, "required": list(REQUIRED), "sections": list(SECTIONS)}


