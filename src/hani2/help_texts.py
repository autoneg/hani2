@dataclass(frozen=True)
class Help:
    """The ``?`` text of one setting."""

    title: str
    #: one line, used as the row's hint
    summary: str
    #: Markdown, shown in the dialog and in the docs
    details: str = ""
    #: the section of the Settings reference it belongs to
    section: str = "Project and study"
    #: the YAML key it sets (empty: the id is the key)
    key: str = ""
    #: a page of the docs with the full rules (``guide/<page>.md#<anchor>``, relative to the guide)
    docs: str = ""
    #: a scheduling dimension whose methods the dialog lists (``opponents``, ``assistants``, ``scenarios``)
    scheduling: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def _normaliser_table() -> str:
    from hani2.evaluation.criteria import NORMALISER_KINDS

    rows = ["| Normaliser | Rule | Default for |", "|---|---|---|"]
    for k, (_, rule, default) in NORMALISER_KINDS.items():
        rows.append(f"| `{k}` | ${rule}$ | {default.replace('|', '/')} |")
    return "\n".join(rows)


