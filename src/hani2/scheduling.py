_DIM_TITLE = {"opponents": "Opponents", "assistants": "Assistants", "scenarios": "Scenarios"}


def markdown_reference() -> str:
    """The generated part of ``docs/guide/scheduling.md``."""
    out = []
    for d in DIMENSIONS:
        out.append(f"## {_DIM_TITLE[d]}\n")
        out.append(f"Default: `{DEFAULTS[d]}`.\n")
        out.append(_table(["Method", "Summary"], [[f"[`{m.key}`](#{d}-{m.key.replace('_', '-')})", m.summary]
                                                  for m in methods(d)]) + "\n")
        for m in methods(d):
            out.append(f"### {m.title} (`{m.key}`) {{#{d}-{m.key.replace('_', '-')}}}\n")
            out.append(f"*{m.summary}*\n")
            out.append(m.details + "\n")
    return "\n".join(out).rstrip() + "\n"


def write_docs(path: str | Path) -> bool:
    """Rewrite the generated part of the docs page; ``True`` when it changed."""
    p = Path(path)
    text = p.read_text()
    a, b = text.index(DOCS_START), text.index(DOCS_END)
    new = text[: a + len(DOCS_START)] + "\n\n" + markdown_reference() + "\n" + text[b:]
    if new != text:
        p.write_text(new)
        return True
    return False


def docs_section(text: str) -> str:
    a, b = text.index(DOCS_START), text.index(DOCS_END)
    return text[a + len(DOCS_START): b].strip() + "\n"


