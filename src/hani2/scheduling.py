_REPORTED: set[str] = set()


def _layer(raw: Any, where: str, errors: list[str]) -> dict[str, str]:
    if raw is None:
        return {}
    if not isinstance(raw, dict):
        errors.append(f"{where}: scheduling must be a mapping of {', '.join(DIMENSIONS)} to method names")
        return {}
    out = {}
    for dim, key in raw.items():
        if dim in OPTIONS:
            continue  # see options_for
        try:
            if dim not in _REGISTRY:
                raise ValueError(f"unknown dimension {dim!r}; use one of {', '.join(DIMENSIONS)}")
            if key is not None and str(key).strip():
                out[dim] = check_method(dim, key)
        except ValueError as e:
            errors.append(f"{where}: {e}")
    return out


def resolve(ref: Any) -> tuple[dict[str, str], dict[str, str], list[str]]:
    """``(effective, explicit, errors)`` for study ``ref``: ``explicit`` holds the
    dimensions set in study.yaml or project.yaml, ``effective`` fills the rest from
    :data:`DEFAULTS`; invalid names are reported in ``errors`` and ignored."""
    from hani2 import projects

    errors: list[str] = []
    explicit: dict[str, str] = {}
    if ref is not None:
        pr = projects.get_project(ref)
        explicit.update(_layer(pr.defaults.get("scheduling"), f"project {pr.name}", errors))
        st = projects.get_study(ref)
        if st is not None:
            explicit.update(_layer(st.overrides.get("scheduling"), f"study {ref}", errors))
    for e in errors:
        if e not in _REPORTED:
            _REPORTED.add(e)
            print(f"[hani2] ERROR: {e} (the default is used)")
    return {**DEFAULTS, **explicit}, explicit, errors


def methods_for(ref: Any) -> dict[str, str]:
    """The method of each dimension for study ``ref`` (``None``: the defaults)."""
    return resolve(ref)[0]


def _options_layer(raw: Any, where: str, errors: list[str]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    if not isinstance(raw, dict):
        return out
    for k in OPTIONS:
        v = raw.get(k)
        if v is None or str(v).strip() == "":
            continue
        try:
            out[k] = check_option(k, v, where)
        except ValueError as e:
            errors.append(str(e))
    return out


def options_for(ref: Any) -> dict[str, Any]:
    """The ``scheduling`` options set in study ``ref``'s files (study over project, each on its
    own); an option no file sets is missing. Invalid values are reported once and ignored."""
    from hani2 import projects

    errors: list[str] = []
    out: dict[str, Any] = {}
    if ref is not None:
        pr = projects.get_project(ref)
        out.update(_options_layer(pr.defaults.get("scheduling"), f"project {pr.name}: scheduling", errors))
        st = projects.get_study(ref)
        if st is not None:
            out.update(_options_layer(st.overrides.get("scheduling"), f"study {ref}: scheduling", errors))
    for e in errors:
        if e not in _REPORTED:
            _REPORTED.add(e)
            print(f"[hani2] ERROR: {e} (ignored)")
    return out


def repeats_allowed(method: str, options: dict[str, Any] | None = None) -> bool:
    """Whether ``method`` may give one human the same Assistant twice: ``assistant_repeats`` when a
    file sets it, else ``True`` only for the methods that repeat by nature (``random_each`` and the
    one-Assistant-per-human methods)."""
    v = (options or {}).get("assistant_repeats")
    if v is not None:
        return bool(v)
    return method not in AT_MOST_ONCE_ASSISTANTS


def repeat_problems(method: str, k: int, pool: Sequence[str], options: dict[str, Any] | None = None) -> list[str]:
    """What breaks the "each Assistant at most once per human" rule: ``k`` counted negotiations
    (``n_required``) over ``pool`` with Assistant method ``method``."""
    opts = options or {}
    n = len(pool)
    if method == "random_each" and opts.get("assistant_repeats") is False:
        return ["scheduling.assistants is 'random_each', which can give a human the same Assistant twice, "
                "but scheduling.assistant_repeats is false; use latin_square, cyclic, balanced_subset or "
                "random_subset, or set assistant_repeats: true"]
    if method in AT_MOST_ONCE_ASSISTANTS and method != EXTERNAL and n and k > n and not repeats_allowed(method, opts):
        return [f"scheduling.assistants is '{method}' with n_required = {k} negotiations but only {n} "
                f"Assistant{'s' if n != 1 else ''} ({', '.join(map(str, pool))}): each Assistant is used at most "
                f"once per human. Lower n_required, add Assistants, or set scheduling.assistant_repeats: true"]
    return []


def _merged_scheduling(*layers: Any) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for layer in layers:
        if isinstance(layer, dict):
            out.update({k: v for k, v in layer.items() if v is not None and str(v).strip() != ""})
    return out


def _file_repeat_problems(project_defaults: dict, overrides: dict | None, ref: Any) -> list[str]:
    from hani2 import groups

    def pick(key: str, default: Any = None) -> Any:
        if overrides is not None and overrides.get(key) is not None:
            return overrides[key]
        v = project_defaults.get(key)
        return default if v is None else v

    sched = _merged_scheduling(project_defaults.get("scheduling"), (overrides or {}).get("scheduling"))
    method = str(sched.get("assistants") or DEFAULTS["assistants"])
    if method not in AT_MOST_ONCE_ASSISTANTS and method != "random_each":
        return []
    opts = {k: check_option(k, sched[k]) for k in OPTIONS if k in sched}
    raw = pick("assistants")
    if raw is None and method != "random_each":
        return []  # the pool comes from the server's settings: unknown here
    try:
        k = int(pick("n_required", 5))
    except (TypeError, ValueError):
        return []
    errors: list[str] = []
    try:
        pool = groups.expand_assistants(raw, ref, errors=errors) if raw is not None else []
    except Exception:  # noqa: BLE001 - a broken group is reported elsewhere
        return []
    if raw is not None and (errors or not pool):
        return []
    return repeat_problems(method, k, pool, opts)


def save_problems(data: dict, nested: str, *, ref: Any = None, project: str | None = None) -> list[str]:
    """What a project.yaml (``nested="defaults"``) or study.yaml (``nested="overrides"``) about to be
    saved breaks about Assistant repeats (``n_required`` > the Assistants for a method that uses each
    at most once, unless ``assistant_repeats: true``). The study's settings are merged with its
    project's; a pool that cannot be expanded here is not checked."""
    from hani2 import projects

    _, settings, _ = projects._split(data, (), nested)
    try:
        if nested == "overrides":
            r = projects.parse_ref(ref) if ref is not None else None
            pname = r.project if r is not None else (project or projects.DEFAULT_PROJECT)
            try:
                pr = projects.load_project(pname)
            except ValueError:
                pr = projects.Project(name=pname)
            with projects.use_study(r):
                return _file_repeat_problems(dict(pr.defaults), settings, r)
        return _file_repeat_problems(settings, None, None)
    except ValueError:
        return []  # bad option values are reported by check_scheduling


def study_repeat_problems(ref: Any) -> list[str]:
    """:func:`save_problems` for a study as it is on disk (a running study only gets a warning)."""
    from hani2 import projects

    if ref is None:
        return []
    r = projects.parse_ref(ref) if isinstance(ref, str) else ref
    pr = projects.get_project(r)
    st = projects.get_study(r)
    try:
        with projects.use_study(r):
            return _file_repeat_problems(dict(pr.defaults), dict(st.overrides) if st is not None else {}, r)
    except ValueError:
        return []


