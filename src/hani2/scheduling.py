def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _slots_table(fn: Callable[[int, int], str], n_slots: int = 3) -> str:
    header = ["Participant"] + [f"Negotiation {k + 1}" for k in range(n_slots)]
    return _table(header, [[str(i)] + [fn(i, k) for k in range(n_slots)] for i in range(_N_PART)])


def _opp_table(method: str) -> str:
    return _slots_table(lambda i, k: pick_opponent(method, _OPP, i, k, seed=f"example|P{i}"))


def _scen_table(method: str) -> str:
    return _slots_table(lambda i, k: pick_scenario_type(method, _TYPES, i, k, seed=f"example|P{i}", counter=k))


_SUBSET_POOL = ["A", "B", "C", "D"]


def _subset_table(method: str, n: int = 6, k: int = 2) -> str:
    plans: list[list[str]] = []
    for i in range(n):
        seed = f"example|P{i}"
        plans.append(random_subset(_SUBSET_POOL, k, seed) if method == "random_subset"
                     else balanced_subset(_SUBSET_POOL, k, plans, seed))
    return _table(["Participant (in order of arrival)"] + [f"Negotiation {j + 1}" for j in range(k)],
                  [[str(i)] + p for i, p in enumerate(plans)])


def _crossing_table(n: int = 3, people: int = 12) -> str:
    methods = {"assistants": "latin_square", "opponents": "latin_square", "scenarios": "by_participant"}
    rows = []
    for i in range(people):
        d = opponent_offset(methods, "shift", n, i)
        rows.append([str(i), str(d)] + [f"{_OPP[latin_index(n, i, k)]} / {pick_opponent('latin_square', _OPP_LOWER, i, k, offset=d)}"
                                        for k in range(n)])
    return _table(["Participant", "Offset $d$"] + [f"Negotiation {k + 1}" for k in range(n)], rows)


_OPP_LOWER = ["a", "b", "c"]


def _assistant_table(method: str, n: int = 6) -> str:
    if method in SUBSET_ASSISTANTS:
        return _subset_table(method)
    if method in PER_NEGOTIATION_ASSISTANTS:
        return _slots_table(lambda i, k: pick_assistant_slot(method, _OPP, i, k, seed=f"example|P{i}"))
    counts: dict[str, int] = {}
    rows = []
    for i in range(n):
        a = pick_assistant_fixed(method, _OPP, i, counts, seed=f"example|P{i}")
        counts[a] = counts.get(a, 0) + 1
        rows.append([str(i), a])
    return _table(["Participant (in order of arrival)", "Assistant (every negotiation)"], rows)


def _williams_rows(n: int) -> str:
    rows = latin_square(n)
    return _table(["Row"] + [f"Position {k + 1}" for k in range(n)],
                  [[str(j)] + [_OPP[x] if n == 3 else str(x) for x in r] for j, r in enumerate(rows)])


