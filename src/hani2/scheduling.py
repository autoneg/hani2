def rng(*parts: Any) -> random.Random:
    """A generator seeded by ``parts`` (the same parts give the same draws in every process)."""
    return random.Random("|".join(str(p) for p in parts))


def latin_square(n: int) -> list[list[int]]:
    from hani2.assignment import latin_square as _ls

    return _ls(n)


def latin_index(n: int, index: int, slot: int) -> int:
    rows = latin_square(n)
    row = rows[index % len(rows)]
    return row[slot % n]


def pick_opponent(method: str, pool: Sequence, index: int, slot: int, seed: str = "", offset: int = 0) -> Any:
    """The opponent of participant ``index`` in counted negotiation ``slot`` (``None`` for ``external``).
    ``offset`` shifts the ``latin_square`` and ``cyclic`` rules (the crossing: :func:`opponent_offset`)."""
    n = len(pool)
    if n == 0 or method == EXTERNAL:
        return None
    custom = _REGISTRY["opponents"].get(method)
    if custom is not None and custom.rule is not None:
        return custom.rule(list(pool), index, slot, seed)
    if method == "latin_square":
        return pool[(latin_index(n, index, slot) + offset) % n]
    if method == "random":
        return rng(seed, "opponents", slot).choice(list(pool))
    if method == "cyclic":
        return pool[(index + slot + offset) % n]
    if method == "fixed_order":
        return pool[slot % n]
    raise ValueError(f"unknown opponents scheduling method {method!r}")


def pick_scenario_type(method: str, types: Sequence[str], index: int, slot: int, seed: str = "",
                       counter: int | None = None, offset: int = 0) -> str | None:
    """The scenario type of participant ``index`` in negotiation ``slot``; ``counter`` is the
    participant's scenario counter (``set_order``). ``None`` for ``external``. ``offset`` shifts
    ``latin_square`` (the crossing: :func:`scenario_offset`)."""
    t = len(types)
    if t == 0 or method == EXTERNAL:
        return None
    custom = _REGISTRY["scenarios"].get(method)
    if custom is not None and custom.rule is not None:
        return custom.rule(list(types), index, slot, seed)
    if method == "by_participant":
        return types[index % t]
    if method == "set_order":
        return types[(slot if counter is None else counter) % t]
    if method == "random":
        return rng(seed, "scenarios", slot).choice(list(types))
    if method == "latin_square":
        return types[(latin_index(t, index, slot) + offset) % t]
    raise ValueError(f"unknown scenarios scheduling method {method!r}")


def pick_assistant_fixed(method: str, pool: Sequence[str], index: int, counts: dict[str, int],
                         seed: str = "") -> str:
    """A new human's fixed Assistant (``balanced``, ``random_fixed``, ``round_robin``)."""
    custom = _REGISTRY["assistants"].get(method)
    if custom is not None and custom.rule is not None:
        return custom.rule(list(pool), index, counts, seed)
    if method == "random_fixed":
        return rng(seed, "assistants").choice(list(pool))
    if method == "round_robin":
        return pool[index % len(pool)]
    return min(pool, key=lambda p: (counts.get(p, 0), list(pool).index(p)))  # balanced


def pick_assistant_each(pool: Sequence[str], slot: int, seed: str = "") -> str:
    """``random_each``: the Assistant of negotiation ``slot``."""
    return rng(seed, "assistants", slot).choice(list(pool))


#: Assistant methods that choose again for every negotiation (within-subjects)
PER_NEGOTIATION_ASSISTANTS = ("random_each", "latin_square", "cyclic", "balanced_subset", "random_subset")
#: Assistant methods that plan a K-subset per human (kept in ``assignments.json``)
SUBSET_ASSISTANTS = ("balanced_subset", "random_subset")
#: Assistant methods that promise each Assistant at most once per human (``assistant_repeats``)
AT_MOST_ONCE_ASSISTANTS = ("latin_square", "cyclic", "balanced_subset", "random_subset", EXTERNAL)
#: opponent methods the crossing shifts
CROSSED_OPPONENTS = ("latin_square", "cyclic")


def pick_assistant_slot(method: str, pool: Sequence[str], index: int, slot: int, seed: str = "") -> str:
    """The Assistant of participant ``index`` in counted negotiation ``slot`` for the
    per-negotiation methods without a stored plan (``random_each``, ``latin_square``, ``cyclic``,
    ``random_subset``). ``balanced_subset`` depends on the humans before: :func:`balanced_subset`."""
    n = len(pool)
    if method == "latin_square":
        return pool[latin_index(n, index, slot)]
    if method == "cyclic":
        return pool[(index + slot) % n]
    if method == "random_subset":
        return random_subset(pool, n, seed)[slot % n]
    if method == "balanced_subset":
        raise ValueError("balanced_subset depends on the humans planned before; use balanced_subset()")
    return pick_assistant_each(pool, slot, seed)


def random_subset(pool: Sequence[str], k: int, seed: str = "") -> list[str]:
    """``random_subset``: the first ``k`` of a seeded random permutation of ``pool`` (at most ``|pool|``)."""
    order = list(pool)
    rng(seed, "assistants", "subset").shuffle(order)
    return order[: max(0, min(k, len(order)))]


#: ``balanced_subset`` enumerates every ordered tuple up to this size (8·7·6·5·4 = 6720), else fills greedily
ENUMERATE_MAX = (8, 5)


def balanced_subset(pool: Sequence[str], k: int, plans: Sequence[Sequence[str]], seed: str = "",
                    opponents: Sequence[Any] | None = None,
                    opponent_plans: Sequence[Sequence[Any] | None] | None = None) -> list[str]:
    """``balanced_subset``: a new human's ordered ``k``-tuple of Assistants from ``pool`` (``k`` is
    capped at ``|pool|``), given the plans of the humans before (``plans``). It minimises, in
    lexicographic order:

    1. the sum of the chosen Assistants' totals so far;
    2. the sum of the pair co-occurrence counts (two Assistants used by the same human) of its pairs;
    3. the sum of the (Assistant, position) counts;
    4. with ``opponents`` (the human's own opponent sequence) and the earlier humans'
       ``opponent_plans``: the sum of the (Assistant, opponent) pair counts;

    ties broken by the RNG seeded with ``seed``. Every ordered tuple is tried for ``|pool| <= 8`` and
    ``k <= 5``; above that the tuple is filled one position at a time with the same criteria."""
    items = list(pool)
    k = max(0, min(k, len(items)))
    totals: Counter = Counter()
    pairs: Counter = Counter()
    pos: Counter = Counter()
    vs: Counter = Counter()
    ops = list(opponent_plans) if opponent_plans is not None else [None] * len(plans)
    for plan, opl in zip(plans, ops + [None] * (len(plans) - len(ops))):
        plan = [str(a) for a in plan]
        for p, a in enumerate(plan):
            totals[a] += 1
            pos[(a, p)] += 1
        for x, y in combinations(sorted(set(plan)), 2):
            pairs[(x, y)] += 1
        if opl:
            for a, o in zip(plan, opl):
                vs[(a, str(o))] += 1
    opp = [str(o) for o in opponents] if opponents else None

    def vs_count(a: str, p: int) -> int:
        return vs[(a, opp[p])] if opp is not None and p < len(opp) else 0

    def score(t: Sequence[str]) -> tuple[int, int, int, int]:
        return (sum(totals[a] for a in t),
                sum(pairs[(x, y)] for x, y in combinations(sorted(t), 2)),
                sum(pos[(a, p)] for p, a in enumerate(t)),
                sum(vs_count(a, p) for p, a in enumerate(t)))

    order = [str(a) for a in items]
    rng(seed, "assistants", "balanced_subset").shuffle(order)  # the tie-break: the first minimum wins
    if len(order) <= ENUMERATE_MAX[0] and k <= ENUMERATE_MAX[1]:
        return list(min(permutations(order, k), key=score)) if k else []
    chosen: list[str] = []
    for p in range(k):
        chosen.append(min((a for a in order if a not in chosen),
                          key=lambda a: (totals[a], sum(pairs[tuple(sorted((a, b)))] for b in chosen),
                                         pos[(a, p)], vs_count(a, p))))
    return chosen


