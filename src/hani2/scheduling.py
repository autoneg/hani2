def design_rows(method: str, n: int) -> int:
    """The rows ``R`` of a counterbalancing design over ``n`` items (``latin_square``: the Williams
    square's ``n`` or ``2n``; ``cyclic``: ``n``; others: 1)."""
    if n <= 0:
        return 1
    if method == "latin_square":
        return len(latin_square(n))
    if method == "cyclic":
        return n
    return 1


def crossing_active(methods: dict[str, str], cross: str) -> bool:
    """Whether the opponent is crossed with the Assistant: ``cross: shift``, a per-negotiation
    Assistant method and a ``latin_square`` or ``cyclic`` opponent method."""
    return (cross == "shift" and methods.get("assistants") in PER_NEGOTIATION_ASSISTANTS
            and methods.get("opponents") in CROSSED_OPPONENTS)


def opponent_offset(methods: dict[str, str], cross: str, n_opponents: int, index: int) -> int:
    """The crossing's block offset ``d(i) = (i // R) mod n_o`` of participant ``index``
    (``R``: the rows of the opponents' design); 0 when the crossing does not apply."""
    if n_opponents < 2 or not crossing_active(methods, cross):
        return 0
    return (index // design_rows(methods["opponents"], n_opponents)) % n_opponents


def scenario_offset(methods: dict[str, str], cross: str, n_types: int, index: int, n_opponents: int = 0) -> int:
    """The scenario type's own block offset ``d_s(i) = (i // B) mod n_s`` for
    ``scenarios: latin_square`` with ``cross: shift`` and a per-negotiation Assistant method:
    ``B = R * n_o`` when the opponents are crossed too (after every full opponent crossing), else
    the rows of the scenario square itself. 0 otherwise."""
    if (n_types < 2 or cross != "shift" or methods.get("scenarios") != "latin_square"
            or methods.get("assistants") not in PER_NEGOTIATION_ASSISTANTS):
        return 0
    if n_opponents >= 2 and crossing_active(methods, cross):
        block = design_rows(methods["opponents"], n_opponents) * n_opponents
    else:
        block = design_rows("latin_square", n_types)
    return (index // block) % n_types


