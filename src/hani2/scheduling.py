"""Scheduling methods: who faces which opponent, which Assistant helps whom, and
which scenario type each negotiation uses.

A study (``study.yaml``) or a project (``project.yaml``, as a default for its
studies) chooses one method per *dimension*::

    scheduling:
      opponents: latin_square   # random, cyclic, fixed_order, external
      assistants: balanced      # random_fixed, random_each, round_robin, external
      scenarios: by_participant # set_order, random, latin_square, external

Each dimension is merged on its own: study, then project, then :data:`DEFAULTS`.
Sessions outside a study keep HANI2's plain behaviour (no study scheduling).
Explicit input from an outside system (a participant's ``schedule.json``) always
wins over the method; ``external`` means *only* that input is used.

Every method is registered with a key, a title, a one-line summary and a Markdown
``details`` text (examples, the rule in LaTeX, advantages and disadvantages); the
admin API (``GET /api/admin/scheduling-methods``), ``hani2 scheduling list`` and
the docs page are built from this registry. ``python -m hani2.scheduling
docs/guide/scheduling.md`` rewrites the generated part of the docs page.
"""

from __future__ import annotations

import random
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Sequence

DIMENSIONS = ("opponents", "assistants", "scenarios")
#: what a study uses when neither it nor its project chooses a method
DEFAULTS = {"opponents": "latin_square", "assistants": "balanced", "scenarios": "by_participant"}
EXTERNAL = "external"
#: recorded (``*_scheduling`` columns) when ``external`` found no outside input and HANI2 filled in
MISSING_SUFFIX = ":missing"
DOCS_START = "<!-- scheduling-methods:start (generated by `python -m hani2.scheduling docs/guide/scheduling.md`) -->"
DOCS_END = "<!-- scheduling-methods:end -->"


@dataclass(frozen=True)
class Method:
    dimension: str
    key: str
    title: str
    summary: str
    details: str
    #: a custom rule (see :func:`register`); the built-in methods have none
    rule: Callable[..., Any] | None = None

    def to_dict(self) -> dict[str, str]:
        return {"key": self.key, "title": self.title, "summary": self.summary, "details": self.details}


_REGISTRY: dict[str, dict[str, Method]] = {d: {} for d in DIMENSIONS}


_TOKEN = re.compile(r"<<(\w+)(?::(\w+))?>>")


def _expand(text: str) -> str:
    """Fill the example tables of a ``details`` text (``<<opp:KEY>>``, ``<<asst:KEY>>``,
    ``<<scen:KEY>>``, ``<<williams:N>>``, ``<<williams_rule>>``)."""

    def sub(m: "re.Match[str]") -> str:
        kind, arg = m.group(1), m.group(2)
        if kind == "opp":
            return _opp_table(arg)
        if kind == "scen":
            return _scen_table(arg)
        if kind == "asst":
            return _assistant_table(arg)
        if kind == "williams":
            return _williams_rows(int(arg))
        if kind == "williams_rule":
            return _WILLIAMS_RULE.strip()
        return m.group(0)

    return _TOKEN.sub(sub, text)


def register(dimension: str, key: str, title: str, summary: str, details: str,
             rule: Callable[..., Any] | None = None) -> Method:
    """Add (or replace) a method of ``dimension``.

    ``rule`` implements a new method: for opponents and scenarios
    ``rule(items, index, slot, seed)`` returns the item of participant ``index`` in
    negotiation ``slot``; for Assistants ``rule(pool, index, counts, seed)`` returns
    the human's fixed Assistant (``counts``: humans per pool member so far)."""
    if dimension not in _REGISTRY:
        raise ValueError(f"unknown scheduling dimension {dimension!r}; use one of {', '.join(DIMENSIONS)}")
    m = Method(dimension, key, title, summary, _expand(details).strip(), rule)
    _REGISTRY[dimension][key] = m
    return m


def methods(dimension: str) -> list[Method]:
    return list(_REGISTRY[check_dimension(dimension)].values())


def method_keys(dimension: str) -> list[str]:
    return list(_REGISTRY[check_dimension(dimension)])


def get_method(dimension: str, key: str) -> Method:
    return _REGISTRY[check_dimension(dimension)][check_method(dimension, key)]


def check_dimension(dimension: str) -> str:
    if dimension not in _REGISTRY:
        raise ValueError(f"unknown scheduling dimension {dimension!r}; use one of {', '.join(DIMENSIONS)}")
    return dimension


def check_method(dimension: str, key: Any) -> str:
    """``key`` when it is a method of ``dimension``, else a ValueError listing the valid ones."""
    check_dimension(dimension)
    k = str(key).strip() if key is not None else ""
    if k not in _REGISTRY[dimension]:
        raise ValueError(f"unknown {dimension} scheduling method {key!r}; use one of "
                         f"{', '.join(_REGISTRY[dimension])}")
    return k


def check_scheduling(value: Any, where: str = "scheduling") -> dict[str, str]:
    """Validate a ``scheduling`` mapping (missing dimensions allowed); returns it cleaned."""
    if value is None:
        return {}
    if not isinstance(value, dict):
        raise ValueError(f"{where} must be a mapping of {', '.join(DIMENSIONS)} to method names")
    out: dict[str, str] = {}
    for dim, key in value.items():
        if dim not in _REGISTRY:
            raise ValueError(f"{where}: unknown dimension {dim!r}; use one of {', '.join(DIMENSIONS)}")
        if key is None or str(key).strip() == "":
            continue
        out[dim] = check_method(dim, key)
    return out


def api_payload() -> dict[str, Any]:
    """``GET /api/admin/scheduling-methods``."""
    return {"dimensions": {d: [m.to_dict() for m in _REGISTRY[d].values()] for d in DIMENSIONS},
            "defaults": dict(DEFAULTS)}


